"""Write paper/inputs/state_display.tex: the state as Euler's 6 x 6 array of officers, generated from data/.

sqrt72 |psi> = sum_{a,b} |ab> (x) |phi_ab>;  |phi_ab> / sqrt2 is the officer of rank a and regiment b in the 12|34
reshaping.  Classical officers (sqrt2 |cd>) are shaded.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, os.pardir))
from ame46real import core  # noqa: E402

terms = core.psi_terms()


def cell(a, b):
    entries = sorted((x[2:], c) for x, c in terms.items() if x[:2] == (a, b))
    if len(entries) == 1 and entries[0][1] == (0, 1):
        return r"\cellcolor{gray!18}$\sqrt2\,\ket{%d%d}$" % entries[0][0]
    out = ""
    for k, (cd, (p, q)) in enumerate(entries):
        assert q == 0 and abs(p) == 1
        out += ("-" if p < 0 else ("+" if k else "")) + r"\ket{%d%d}" % cd
    return "$" + out + "$"


lines = [r"% generated by paper/make_state_table.py from data/psi_terms.json -- do not edit",
         r"\begin{center}",
         r"\renewcommand{\arraystretch}{1.4}\setlength{\tabcolsep}{8pt}",
         r"\begin{tabular}{c|cccccc}",
         r"$\ket{\phi_{ab}}$ & $b=0$ & $b=1$ & $b=2$ & $b=3$ & $b=4$ & $b=5$\\\hline"]
for a in range(6):
    lines.append(r"$a=%d$ & " % a + " & ".join(cell(a, b) for b in range(6)) + r"\\")
lines += [r"\end{tabular}", r"\end{center}"]
open(os.path.join(HERE, "inputs", "state_display.tex"), "w").write("\n".join(lines) + "\n")
print("wrote paper/inputs/state_display.tex")
