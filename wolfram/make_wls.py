"""Generate verify_families.wls from data/family.json: a symbolic Mathematica check that the closed forms
psi_sigma(delta, theta) (sigma = +-1, delta = cos 2 al) and psi_face(theta) are AME(4,6) for ALL parameter values,
i.e. M.M^dagger = I/36 for every 2|2 reshaping M.  A negative control (one amplitude multiplied by i) must fail.

  python wolfram/make_wls.py && wolframscript -file wolfram/verify_families.wls
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), os.pardir))
from ame46real import family as fam  # noqa: E402


def phase(row):
    t = "".join(f"{'+' if c > 0 else '-'}{abs(c) if abs(c) != 1 else ''}th{j + 1}" for j, c in enumerate(row) if c)
    return t or "0"


def rules(entries):
    return "{" + ",\n ".join(f"{{{','.join(str(c + 1) for c in x)}}} -> {a}" for x, a in entries) + "}"


out = ['(* generated by make_wls.py from data/family.json *)',
       'cuts = {{1, 2, 3, 4}, {1, 3, 2, 4}, {1, 4, 2, 3}};',
       'tensor[r_] := Normal[SparseArray[r, {6, 6, 6, 6}]];',
       'cutMatrix[t_, p_] := ArrayReshape[Transpose[t, Ordering[p]], {36, 36}];',
       'check[r_, name_] := Module[{t = tensor[r], res},',
       '  res = Table[Module[{m = cutMatrix[t, p]},',
       '      Max[Abs[Flatten[Simplify[TrigReduce[ExpToTrig[ComplexExpand[m . ConjugateTranspose[m]] - IdentityMatrix[36]/36]]]]]]],',
       '    {p, cuts}];',
       '  Print[name, ": ", res, "  -> AME for all parameters: ", res === {0, 0, 0}]; res === {0, 0, 0}];']
for sigma in (1, -1):
    ent = []
    for q, t in enumerate(fam.TYPE):
        mod = {"L": str(int(fam.EPS[q])), "O": "Sqrt[2] Cos[al]", "N": f"({'' if sigma > 0 else '-'}I) Sqrt[2] Sin[al]"}[t]
        ent.append((fam.POINTS[q], f"({mod}) Exp[I ({phase(fam.K[q])})]/Sqrt[72]"))
    out.append(f"r72{'p' if sigma > 0 else 'm'} = {rules(ent)};")
Kf = fam.face_K()
ent = [(fam.POINTS[q], f"({int(fam.EPS[q]) if fam.TYPE[q] == 'L' else 'Sqrt[2]'}) Exp[I ({phase(Kf[i])})]/Sqrt[72]")
       for i, q in enumerate(fam.S60)]
out.append(f"r60 = {rules(ent)};")
out += ['ok = {check[r72p, "psi_+(delta, theta), delta = cos 2al"], check[r72m, "psi_-(delta, theta)"],',
        '      check[r60, "psi_face(theta)"]};',
        'bad = check[ReplacePart[r60, {1, 2} -> I r60[[1, 2]]], "negative control (one entry times i; must FAIL)"];',
        'Print[If[And @@ ok && ! bad, "ALL SYMBOLIC CHECKS PASSED", "SYMBOLIC CHECK FAILED"]];']
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "verify_families.wls"), "w").write("\n".join(out) + "\n")
print("wrote wolfram/verify_families.wls")
